const SORTED_ALIASES = [...COUNTRY_ISO_ALIASES].sort((a, b) => b[0].length - a[0].length);

const normalizeCountryKey = (value: string): string =>
    String(value || '')
        .trim()
        .toLowerCase()
        .replace(/\s+/g, ' ');

/** Resolve a destination/country label to an ISO country code. */
export const resolveCountryIsoCode = (label?: string | null): string | null => {
    const raw = String(label || '').trim();
    if (!raw) return null;

    const canonical = resolveWorldCountryName(raw);
    const canonicalIso = COUNTRY_NAME_TO_ISO[normalizeCountryKey(canonical)];
    if (canonicalIso) return canonicalIso;

    const directIso = COUNTRY_NAME_TO_ISO[normalizeCountryKey(raw)];
    if (directIso) return directIso;

    const normalized = raw.toUpperCase();
    for (const [alias, iso] of SORTED_ALIASES) {
        if (normalized.includes(alias)) return iso;
    }

    return null;
};

/** Cross-platform flag image URL (works on Windows, macOS, Linux). */
export const getCountryFlagImageUrl = (iso: string, width: 20 | 40 | 80 = 20): string =>
    `https://flagcdn.com/w${width}/${iso.toLowerCase()}.png`;

export const getCountryFlagImageForLabel = (
    label?: string | null,
    width: 20 | 40 | 80 = 20
): string | null => {
    const iso = resolveCountryIsoCode(label);
    return iso ? getCountryFlagImageUrl(iso, width) : null;
};
